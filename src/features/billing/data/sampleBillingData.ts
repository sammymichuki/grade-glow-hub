function buildInvoice(input: {
  id: string;
  number: string;
  customerId: string;
  customerName: string;
  currency: 'KES' | 'USD' | 'GBP' | 'EUR';
  lines: Array<{ description: string; quantity: number; unitPriceMinor: number }>;
  taxRateBp: number;
  status: Invoice['status'];
  issuedAt: string;
  dueAt: string;
  paidAt: string | null;
  paymentProvider: Invoice['paymentProvider'];
  relatedIntentId: string | null;
}): Invoice {
  const lines: InvoiceLine[] = input.lines.map((line) => ({
    ...line,
    amountMinor: line.quantity * line.unitPriceMinor,
  }));
  const subtotalMinor = lines.reduce((total, line) => total + line.amountMinor, 0);
  const taxMinor = Math.floor((subtotalMinor * input.taxRateBp + 5_000) / 10_000);
  return {
    id: input.id,
    number: input.number,
    customerId: input.customerId,
    customerName: input.customerName,
    status: input.status,
    currency: input.currency,
    lines,
    subtotalMinor,
    taxMinor,
    totalMinor: subtotalMinor + taxMinor,
    issuedAt: input.issuedAt,
    dueAt: input.dueAt,
    paidAt: input.paidAt,
    paymentProvider: input.paymentProvider,
    relatedIntentId: input.relatedIntentId,
  };
}

