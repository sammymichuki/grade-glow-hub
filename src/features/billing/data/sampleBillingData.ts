function buildSamplePayout(input: {
  creatorId: string;
  periodStart: string;
  periodEnd: string;
  currency: PayoutRecord['currency'];
  grossMinor: number;
  feeMinor: number;
  withholdingRateBp: number;
  method: PayoutMethod;
  status: PayoutStatus;
  paidAt?: string;
  reference?: string;
}): PayoutRecord {
  const creatorNetMinor = Math.floor((input.grossMinor * 8_000) / 10_000);
  const commissionMinor = input.grossMinor - creatorNetMinor;
  const feeMinor = Math.min(input.feeMinor, creatorNetMinor);
  const withholdingMinor = Math.min(
    Math.floor((creatorNetMinor * input.withholdingRateBp + 5_000) / 10_000),
    creatorNetMinor - feeMinor
  );
  return {
    id: `po_${input.creatorId}_${input.periodStart.slice(0, 7)}_${input.method}`,
    creatorId: input.creatorId,
    periodStart: input.periodStart,
    periodEnd: input.periodEnd,
    currency: input.currency,
    grossMinor: input.grossMinor,
    commissionMinor,
    creatorNetMinor,
    feeMinor,
    withholdingMinor,
    disbursementMinor: creatorNetMinor - feeMinor - withholdingMinor,
    method: input.method,
    status: input.status,
    scheduledFor: input.periodEnd,
    paidAt: input.paidAt ?? null,
    reference: input.reference ?? null,
  };
}

